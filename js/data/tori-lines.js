// 템플릿 채우기: {name}, {quote}, {j:키:이/가}

export function fill(template, vars = {}) {
  return String(template)
    .replace(/\{j:(\w+):([^}]+)\}/g, (m, key, pair) => josa(String(vars[key] ?? ''), pair))
    .replace(/\{(\w+)\}/g, (m, key) => (vars[key] !== undefined ? String(vars[key]) : ''))
    .replace(/\s{2,}/g, ' ')
    .trim();
}
